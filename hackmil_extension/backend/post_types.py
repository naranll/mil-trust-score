"""
Постын төрөл ангилах (decision tree) ба зар/худалдааны луйврын шалгалт.

Дараалал (тохирсон шийдвэр Q11):
    Пост
     ├─ Facebook «Sponsored» / CTA товч ("Send message", "Shop now")  → ad        (📢 Зар)
     ├─ Худалдааны шинж (₮, захиалга, inbox, хүргэлт, промо код …)   → commerce  (🛍 Худалдаа/инфлюенсер)
     ├─ Мэдэгдлийн шинж (тоо, байгууллага, эрүүл мэнд, мөнгө, төр …)  → claim     (📰 одоогийн оноо)
     └─ бусад                                                          → personal  (юу ч харуулахгүй)
Текстгүй, зөвхөн зураг/видео постыг extension өөрөө (media) гэж шийднэ.

Зар «үнэн» гэж батлагддаггүй тул ногоон өгөхгүй. Гурван төлөв:
    ad_scam  — Луйврын эрсдэл өндөр        (улаан)
    ad_check — Худалдан авахаас өмнө шалга (шар)
    ad_ok    — Зар · луйврын шинж илрээгүй (нил ягаан/саарал)
"""
import re

# ---------------------------------------------------------------------------
# 1. Ангилах шинжүүд
# ---------------------------------------------------------------------------
# Хүчтэй худалдааны шинж — нэг нь л байхад хангалттай
# ₮ дүн дангаараа хүчтэй шинж БИШ: «100.000₮-р торгоно», «27000₮ төлнө» гэх мэт мэдээнд ч гардаг
COMMERCE_STRONG = re.compile(
    r"\d[\d,. ]*\s*(₮|төг\b|төгрөг\S*)\s*-?(өөс|аас|оос)\s*эх|үнэ\s*[:：~-]\s*\d[\d,. ]*₮?|inbox|инбокс|хүргэлт(тэй|ээр)|"
    r"промо\s*код|promo\s*code|\bзарна\b|худалдана|захиалга авч|захиалаарай|\bsale\b|\d+\s*%\s*(off|хямд)|"
    r"paid partnership|төлбөртэй хамтын ажиллагаа|#зар\b|#sponsored|онлайн shop|online shop|элсэлт авч|бүртгүүлээрэй", re.I)
# Сул шинж — мэдээнд ч гардаг тул 2 ба түүнээс дээш байх ёстой
#   «үнэ»-ийн хувилбарууд л: «үнэн», «үнэхээр», «үнэгүй», «үнэ төлбөргүй» нь худалдааны шинж биш
COMMERCE_WEAK = re.compile(r"\d[\d,. ]*\s*(₮|төг\b|төгрөг)|\bүнэ\b(?!\s*төлбөргүй)|\bүн(ийн|ийг|ээр|этэй)\b|хямдрал|дэлгүүр|бараа|бүтээгдэхүүн|ширхэг|захиал|бэлэн байгаа|өнгө(нүүд)? байна|размер|хэмжээ\s*:", re.I)
COMMERCE_RE = COMMERCE_STRONG   # ad_score-ийн тайлбарт

# Мэдэгдлийн шинж (монгол хэлний нөхцөлд тааруулж ҮНДСЭЭР нь: «засгийн газ» → газар/газрын)
CLAIM_RE = re.compile(
    r"\d|яам|засгийн газ|\bуих\b|их хурал|хурал|ерөнхийлөгч|ерөнхий сайд|сайд|дэмб|банк|цагдаа|шүүх|прокурор|"
    r"\bэм\b|эмч|вакцин|хавдар|өвчин|эмчил|эдгэр|вирус|халдвар|\bхор|баривч|хэрэгт|гэмт|осол|түймэр|нас бар|амь|"
    r"сая|тэрбум|мөнгө|тэтгэмж|тэтгэвэр|татвар|зээл|хууль|тогтоол|шийдвэр|сонгууль|\bнам\b|\bман\b|\bан\b|"
    r"шэйр|хуваалц|тараа|яаралтай|анхаар|сэрэмжлүүл|мэдээлэл|судалгаа|эрдэмтэд|тогтоогдсон|"
    r"[А-ЯЁӨҮ]\.[А-ЯЁӨҮ][а-яёөү]+|хятад|орос|америк|япон|солонгос|уран|нүүрс", re.I)
# Худалдааны үгийг ИШЛЭЖ мэдээлсэн («“...зарна” гэх хуурамч зар», «үнэ нэмэгдлээ») → худалдааны пост биш
REPORT_RE = re.compile(r"хуурамч зар|залилан|анхаарууллаа|мэдээллээ|гэх (зар|пост|мэдээлэл)|инфляц|татвар|торго|цалин|"
                       r"тэтгэвэр|үн(э|ийг|ийн)\s*(нэмэгд|нэмсэн|нэмж|өс)", re.I)
ECON_NEWS_RE = re.compile(r"статистик|хувиар|тэрбум|их наяд|ам\.?доллар|байдлаар|\[ОН\]|\bоны\b|хорооноос|\bХК\b|ХХК|ТӨХК|ББСБ|арилжаа|экспорт|импорт")
# Нэгдүгээр биеэр бичсэн ч мэдэгдэл/зөвлөгөө/гуйлт агуулсан (сураг алга, «үүнийг түрх», «битгий ид») → шалгана
ADVICE_RE = re.compile(r"үнэгүй|битгий|\bбүү\b|авраач|сураг|алга бол|байда(г|гү)й|олдохгүй|түрх|\bуу(х|ж|гаарай)|идэ(х|ж|эрэй)|"
                       r"хэрэглэ|үр дүн|гайхш|мэдэж ав|анхаар|галт зэвсэг|тулалд|дайн|эх орон|ашиг хүртэгч|холбогдо|нууцаар|"
                       r"❗|‼|!{2,}", re.I)
# Хувийн/энгийн постын шинж
PERSONAL_RE = re.compile(
    r"(^|\s)(би|бид|миний|манай гэр|минь|намайг|надад|бидний|ээж|аав|найзууд(аа)?)(\s|$|,)|төрсөн өдр|баяр хүргэ|"
    r"амжилт хүсье|хайртай|санаж байна|баярлалаа|сайхан өдөр|амралт(аа)?|аялал(аа)?|гэр бүл(ээрээ|тэйгээ)|"
    r"[😍🥰❤️😂🤣🙏🎉🎂]", re.I)


def rule_classify(text, sponsored=False, has_cta=False):
    """Буцаах: (төрөл, яагаад) — тайлбар нь хэрэглэгчид «яагаад зар гэж үзсэн бэ» гэдгийг хэлнэ.
    Анхдагч нь «мэдэгдэл»: эргэлзээтэй үед шалгах нь, худлыг алгасахаас дээр."""
    t = text or ""
    if sponsored:
        return "ad", "Facebook энэ постыг «Sponsored» (төлбөртэй зар) гэж тэмдэглэсэн"
    if has_cta:
        return "ad", "Постод «Мессеж илгээх / Худалдан авах» гэх мэт зарын товч байна"
    reported = REPORT_RE.search(t)
    m = COMMERCE_STRONG.search(t)
    if m and not reported:
        return "commerce", f"Худалдааны шинж илэрсэн: «{m.group(0).strip()}»"
    # Нэг шинж нэг л удаа тоологдоно: «4750₮ … 84,000₮» нь хоёр биш, нэг шинж (үнэ дурдсан)
    weak = {}
    for w in COMMERCE_WEAK.finditer(t):
        weak.setdefault("₮" if w.group(1) else w.group(0).lower(), w.group(0).strip())
    # Эдийн засгийн мэдээ ч «бараа, үнэ» гэж бичдэг → статистик/байгууллагын хэллэгтэй бол худалдаа биш
    if len(weak) >= 2 and not ECON_NEWS_RE.search(t) and not reported:
        return "commerce", "Худалдааны шинж илэрсэн: «" + "», «".join(sorted(weak.values())[:2]) + "»"
    # Хувийн пост: хувийн хэллэгтэй, мэдэгдэл/зөвлөгөө/гуйлт агуулаагүй, богино
    if PERSONAL_RE.search(t) and not CLAIM_RE.search(t) and not ADVICE_RE.search(t) and len(t.split()) <= 30:
        return "personal", ""
    return "claim", ""


# ---------------------------------------------------------------------------
# ML + дүрэм хосолсон ангилагч
#   Хүчтэй дүрэм (Sponsored, CTA, үнэ ₮, inbox …) үргэлж ялна — тайлбарлах боломжтой.
#   ML нь зөвхөн дүрэм «мэдэгдэл» гэсэн үед «энэ үнэндээ хувийн пост/худалдаа юу?» гэж нарийвчилна.
#   Итгэлгүй үед (p < босго) дүрмийн хариу хэвээр → «эргэлзээтэй бол шалга» зарчим.
# ---------------------------------------------------------------------------
from pathlib import Path as _P
try:
    import joblib as _jl
    _TM = _jl.load(_P(__file__).resolve().parent / "type_model.joblib")
except Exception:          # загвар байхгүй бол зөвхөн дүрэм
    _TM = None
P_PERSONAL, P_COMMERCE = 0.75, 0.80


def classify(text, sponsored=False, has_cta=False):
    kind, why = rule_classify(text, sponsored, has_cta)
    if kind != "claim" or _TM is None or not text:
        return kind, why
    probs = dict(zip(_TM.classes_, _TM.predict_proba([text])[0]))
    # Зөвлөгөө, гуйлт, анхааруулга агуулсан бол хувийн хэллэгтэй ч шалгана
    if probs.get("personal", 0) >= P_PERSONAL and not ADVICE_RE.search(text):
        return "personal", ""
    if probs.get("commerce", 0) >= P_COMMERCE and COMMERCE_WEAK.search(text) and not REPORT_RE.search(text):
        return "commerce", f"Худалдааны пост шиг харагдаж байна (загвар {probs['commerce']:.0%} итгэлтэй)"
    return kind, why


