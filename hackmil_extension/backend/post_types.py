    ("ad_inbox_only", r"зөвхөн\s*(inbox|инбокс|чат|мессеж)|inbox-?(оор|ээр)\s*(холбогдо|захиал|асуу)|үнэ(ийг)?\s*inbox|\bdm\b", 1),
