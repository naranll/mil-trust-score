PROMO_RE = re.compile(r"промо\s*код|promo\s*code|код(оор|ыг)?\s*[A-ZА-Я0-9]{3,}|хөнгөлөлтийн код", re.I)
SHORTENERS = re.compile(r"bit\.ly|tinyurl|t\.ly|cutt\.ly|shorturl|is\.gd|rb\.gy", re.I)
# Банк, оператор, алдартай брэндийг нэрээр нь ашигласан бэлэг/мөнгө тараах пост = түгээмэл луйвар
BRANDS = re.compile(r"хаан банк|голомт|худалдаа хөгжлийн|төрийн банк|хас банк|юнител|unitel|мобиком|mobicom|"
                    r"скайтел|g-?mobile|samsung|apple|iphone|монголбанк|e-?mongolia|ндш|нийгмийн даатгал", re.I)


def _found(rx, text):
    m = re.search(rx, text, re.I)
    if not m:
        return None
    a, b = m.span()
    return text[a:b].strip()[:40]


def ad_score(text, post_type, author_kind="unknown", link=None, link_title=None):
    """Зар/худалдааны пост: луйврын ба итгэл нэмэх шинжийг ХОЁУЛАНГ нь буцаана"""
    t = text or ""
    scam, legit, weight = [], [], 0
    for sid, rx, w in SCAM:
        f = _found(rx, t)
        if f:
            scam.append({"id": sid, "found": f}); weight += w
    if link and SHORTENERS.search(link) and not any(s["id"] == "ad_short_link" for s in scam):
        scam.append({"id": "ad_short_link", "found": link[:40]}); weight += 1
    if link and link.lower().startswith("http://"):
        scam.append({"id": "ad_no_https", "found": link[:40]}); weight += 1
    b = BRANDS.search(t)
    # Үнэ дурдсан нь хэвийн (iPhone зардаг дэлгүүр) — зөвхөн бэлэг/мөнгө ТАРААХ үед
    if b and re.search(r"бэлэг|хонжвор|азтан|үнэгүй|(мөнгө|₮|төгрөг).{0,20}(өгнө|тараа|олгоно|хийнэ)", t, re.I) and author_kind != "trusted":
        scam.append({"id": "ad_brand_bait", "found": b.group(0)}); weight += 2
    # Инфлюенсер: промо код өгсөн мөртлөө сурталчилгаа гэдгээ зарлаагүй
    disclosed = re.search(LEGIT[-1][1], t, re.I)
    if PROMO_RE.search(t) and not disclosed and post_type == "commerce":
        scam.append({"id": "ad_hidden_promo", "found": _found(PROMO_RE.pattern, t)}); weight += 1

    for sid, rx in LEGIT:
        f = _found(rx, t)
        if f:
            legit.append({"id": sid, "found": f})
    if link and link.lower().startswith("https://") and not SHORTENERS.search(link) and "facebook.com" not in link:
        host = re.sub(r"^https://(www\.)?", "", link.lower()).split("/")[0]
        legit.append({"id": "ad_website", "found": host})
    if author_kind == "trusted":
        legit.append({"id": "ad_trusted_page", "found": ""})

    # Төлөв: хүчтэй шинж (жин ≥3: карт асуух, урьдчилгаа+inbox, бэлэг+шэйр …) → улаан
    if weight >= 3 or any(s["id"] in ("ad_card_data",) for s in scam):
        state = "ad_scam"
    elif scam or not legit:
        state = "ad_check"
    else:
        state = "ad_ok"
    return {"state": state, "scam": scam, "legit": legit, "weight": weight}


